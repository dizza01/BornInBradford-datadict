def _load_triples(path: Path) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Triples file not found: {path}")

    rows: list[dict[str, Any]] = []
    skipped_rows_preview: list[dict[str, Any]] = []
    rows_read = 0
    skipped_missing_required = 0

    with path.open("r", encoding="utf-8") as fh:
        for line_no, line in enumerate(fh, start=1):
            line = line.strip()
            if not line:
                continue
            rows_read += 1
            try:
                rec = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON at line {line_no}: {exc}") from exc

            if not rec.get("question") or not rec.get("source_chunk_id"):
                skipped_missing_required += 1
                if len(skipped_rows_preview) < 5:
                    skipped_rows_preview.append(
                        {
                            "line_no": line_no,
                            "query_id": rec.get("query_id", ""),
                            "question_present": bool(rec.get("question")),
                            "source_chunk_id_present": bool(rec.get("source_chunk_id")),
                        }
                    )
                continue
            rows.append(rec)

    input_summary = {
        "rows_read": rows_read,
        "rows_loaded": len(rows),
        "rows_skipped_missing_required": skipped_missing_required,
        "skipped_rows_preview": skipped_rows_preview,
    }
    return rows, input_summary


def _safe_median(values: list[int]) -> float | None:
    if not values:
        return None
    return float(statistics.median(values))


def _safe_percentile(values: list[float], percentile: float) -> float | None:
    if not values:
        return None
    if percentile <= 0:
        return float(min(values))
    if percentile >= 100:
        return float(max(values))

    ordered = sorted(values)
    rank = math.ceil((percentile / 100.0) * len(ordered))
    idx = max(0, min(len(ordered) - 1, rank - 1))
    return float(ordered[idx])


def _ndcg_at_k_binary(retrieved_ids: list[str], source_chunk_id: str, k: int) -> float:
    if k <= 0 or not source_chunk_id:
        return 0.0

    for rank, chunk_id in enumerate(retrieved_ids[:k], start=1):
        if chunk_id == source_chunk_id:
            return 1.0 / math.log2(rank + 1)
    return 0.0


def _precision_at_k_binary(retrieved_ids: list[str], source_chunk_id: str, k: int) -> float:
    if k <= 0 or not source_chunk_id:
        return 0.0
    relevant = sum(1 for chunk_id in retrieved_ids[:k] if chunk_id == source_chunk_id)
    return relevant / k


def _safe_run_name(run_name: str) -> str:
    safe = re.sub(r"[^a-zA-Z0-9._-]+", "_", run_name.strip())
    return safe.strip("_") or "run"


def _json_compact(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


