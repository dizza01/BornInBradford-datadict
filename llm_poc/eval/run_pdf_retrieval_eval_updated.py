def _tokenize(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+", (text or "").lower())


def _rrf_fuse(rank_lists: list[list[str]], rrf_k: int) -> list[str]:
    scores: dict[str, float] = defaultdict(float)
    for ranked_ids in rank_lists:
        for rank, doc_id in enumerate(ranked_ids, start=1):
            scores[doc_id] += 1.0 / (rrf_k + rank)
    return [doc_id for doc_id, _ in sorted(scores.items(), key=lambda kv: kv[1], reverse=True)]


class SparseBM25:
    def __init__(self, ids: list[str], docs: list[str], k1: float = 1.2, b: float = 0.75):
        self.ids = ids
        self.k1 = k1
        self.b = b
        self.n_docs = len(ids)
        self.doc_len: list[int] = []
        self.avgdl = 0.0
        self.postings: dict[str, list[tuple[int, int]]] = defaultdict(list)
        self.df: dict[str, int] = {}
        self.idf: dict[str, float] = {}
        self._build(docs)

    def _build(self, docs: list[str]) -> None:
        total_len = 0
        for idx, text in enumerate(docs):
            tokens = _tokenize(text)
            total_len += len(tokens)
            self.doc_len.append(len(tokens))

            counts = Counter(tokens)
            for term, tf in counts.items():
                self.postings[term].append((idx, tf))

        self.avgdl = (total_len / self.n_docs) if self.n_docs else 0.0

        for term, plist in self.postings.items():
            df = len(plist)
            self.df[term] = df
            # Standard BM25 IDF variant
            self.idf[term] = math.log(1.0 + ((self.n_docs - df + 0.5) / (df + 0.5)))

    def search(self, query: str, top_n: int) -> list[str]:
        if top_n <= 0 or not query:
            return []
        if self.n_docs == 0:
            return []

        scores: dict[int, float] = defaultdict(float)
        for term in _tokenize(query):
            plist = self.postings.get(term)
            if not plist:
                continue
            idf = self.idf.get(term, 0.0)
            for doc_idx, tf in plist:
                dl = self.doc_len[doc_idx] if doc_idx < len(self.doc_len) else 0
                denom = tf + self.k1 * (1.0 - self.b + self.b * (dl / (self.avgdl or 1.0)))
                scores[doc_idx] += idf * ((tf * (self.k1 + 1.0)) / (denom or 1.0))

        ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)[:top_n]
        return [self.ids[idx] for idx, _ in ranked]


def _simple_rerank_score(query: str, doc: str) -> float:
    q_tokens = _tokenize(query)
    d_tokens = _tokenize(doc)
    if not q_tokens or not d_tokens:
        return 0.0

    q_set = set(q_tokens)
    d_set = set(d_tokens)
    overlap = len(q_set & d_set) / max(1, len(q_set))

    q_bigrams = set(zip(q_tokens, q_tokens[1:]))
    d_bigrams = set(zip(d_tokens, d_tokens[1:]))
    bigram_overlap = len(q_bigrams & d_bigrams) / max(1, len(q_bigrams)) if q_bigrams else 0.0

    contains_query = 1.0 if query.lower().strip() in doc.lower() else 0.0

    return (0.65 * overlap) + (0.25 * bigram_overlap) + (0.10 * contains_query)


def _load_cross_encoder(
    model_name: str,
    max_length: int,
    trust_remote_code: bool,
) -> Any:
    try:
        from sentence_transformers import CrossEncoder
    except ImportError as exc:
        raise RuntimeError(
            "Cross-encoder reranking requires sentence-transformers. "
            "Install it with: pip install sentence-transformers"
        ) from exc

    try:
        return CrossEncoder(
            model_name,
            max_length=max_length,
            trust_remote_code=trust_remote_code,
        )
    except TypeError:
        # Older sentence-transformers versions may not expose trust_remote_code.
        if trust_remote_code:
            raise
        return CrossEncoder(model_name, max_length=max_length)


def _cross_encoder_rerank(
    query: str,
    candidate_ids: list[str],
    doc_by_id: dict[str, str],
    cross_encoder: Any,
    batch_size: int,
) -> list[str]:
    pairs = [(query, doc_by_id.get(doc_id, "")) for doc_id in candidate_ids]
    if not pairs:
        return []

    scores = cross_encoder.predict(
        pairs,
        batch_size=max(1, int(batch_size)),
        show_progress_bar=False,
    )
    scored = zip(candidate_ids, [float(score) for score in scores])
    return [doc_id for doc_id, _ in sorted(scored, key=lambda kv: kv[1], reverse=True)]


def _build_summary(per_query: list[dict[str, Any]], top_k: list[int]) -> dict[str, Any]:
    n = len(per_query)
    first_hit_ranks = [q["hit_rank"] for q in per_query if q["hit_rank"]]
    latencies_ms = [float(q["latency_ms"]) for q in per_query if q.get("latency_ms") is not None]

    recall_at_k = {
        str(k): (sum(1 for q in per_query if q[f"hit_at_{k}"]) / n if n else 0.0)
        for k in top_k
    }
    ndcg_at_k = {
        str(k): (
            sum(
                _ndcg_at_k_binary(
                    retrieved_ids=q.get("retrieved_ids", []),
                    source_chunk_id=str(q.get("source_chunk_id", "")),
                    k=k,
                )
                for q in per_query
            )
            / n
            if n
            else 0.0
        )
        for k in top_k
    }
    precision_at_k = {
        str(k): (
            sum(
                _precision_at_k_binary(
                    retrieved_ids=q.get("retrieved_ids", []),
                    source_chunk_id=str(q.get("source_chunk_id", "")),
                    k=k,
                )
                for q in per_query
            )
            / n
            if n
            else 0.0
        )
        for k in top_k
    }
    mrr = (sum(1.0 / q["hit_rank"] for q in per_query if q["hit_rank"]) / n) if n else 0.0

    return {
        "n_queries": n,
        "top_k": top_k,
        "recall_at_k": recall_at_k,
        "mrr": mrr,
        "avg_hit_rank": (sum(first_hit_ranks) / len(first_hit_ranks)) if first_hit_ranks else None,
        "median_hit_rank": _safe_median(first_hit_ranks),
        "ndcg_at_k": ndcg_at_k,
        "precision_at_k": precision_at_k,
        "latency_p50_ms": _safe_percentile(latencies_ms, 50),
        "latency_p95_ms": _safe_percentile(latencies_ms, 95),
    }


def evaluate_retrieval_side_by_side(
    triples: list[dict[str, Any]],
    top_k: list[int],
    modes: list[str],
    dense_pool: int,
    sparse_pool: int,
    rerank_pool: int,
    rrf_k: int,
    cross_encoder_model: str,
    cross_encoder_batch_size: int,
    cross_encoder_max_length: int,
    cross_encoder_trust_remote_code: bool,
) -> dict[str, Any]:
    top_k = sorted({k for k in top_k if k > 0})
    if not top_k:
        raise ValueError("top_k must contain at least one positive integer")

    allowed_modes = {
        "dense",
        "hybrid",
        "hybrid_rerank",
        "dense_cross_encoder",
        "hybrid_cross_encoder",
    }
    requested_modes = []
    seen = set()
    for mode in modes:
        m = mode.strip().lower()
        if m in allowed_modes and m not in seen:
            requested_modes.append(m)
            seen.add(m)
    if not requested_modes:
        raise ValueError(
            "At least one valid mode is required: dense, hybrid, hybrid_rerank, "
            "dense_cross_encoder, hybrid_cross_encoder"
        )

    max_k = max(top_k)
    dense_pool = max(dense_pool, max_k)
    sparse_pool = max(sparse_pool, max_k)
    rerank_pool = max(rerank_pool, max_k)

    client = get_chroma_client()
    collection = client.get_collection("bib_papers")

    # Build sparse/document cache only when rerank modes need it.
    sparse_index: SparseBM25 | None = None
    doc_by_id: dict[str, str] = {}
    needs_sparse = any(m in requested_modes for m in ("hybrid", "hybrid_rerank", "hybrid_cross_encoder"))
    needs_docs = any(m in requested_modes for m in ("hybrid", "hybrid_rerank", "dense_cross_encoder", "hybrid_cross_encoder"))
    if needs_sparse or needs_docs:
        sparse_source = collection.get(where={"source": "pdf_fulltext"}, include=["documents"])
        sparse_ids = sparse_source.get("ids", []) or []
        sparse_docs = sparse_source.get("documents", []) or []
        doc_by_id = {doc_id: doc for doc_id, doc in zip(sparse_ids, sparse_docs)}
    if needs_sparse:
        sparse_index = SparseBM25(sparse_ids, sparse_docs)

    cross_encoder = None
    if any(m in requested_modes for m in ("dense_cross_encoder", "hybrid_cross_encoder")):
        cross_encoder = _load_cross_encoder(
            model_name=cross_encoder_model,
            max_length=max(64, int(cross_encoder_max_length)),
            trust_remote_code=bool(cross_encoder_trust_remote_code),
        )

    by_mode_per_query: dict[str, list[dict[str, Any]]] = {m: [] for m in requested_modes}
    attempted_queries = 0
    succeeded_queries = 0
    failed_queries: list[dict[str, Any]] = []

    for idx, triple in enumerate(triples, start=1):
        question = str(triple.get("question", "")).strip()
        source_chunk_id = str(triple.get("source_chunk_id", "")).strip()
        query_id = str(triple.get("query_id", f"q_{idx}"))
        question_type = triple.get("question_type", "")

        if not question or not source_chunk_id:
            continue

        attempted_queries += 1

        try:
            t0 = time.perf_counter()
            dense_result = collection.query(
                query_texts=[question],
                n_results=max(dense_pool, max_k),
                where={"source": "pdf_fulltext"},
                include=[],
            )
            dense_ids = dense_result.get("ids", [[]])[0] or []
            dense_latency_ms = (time.perf_counter() - t0) * 1000.0

            t1 = time.perf_counter()
            sparse_ids = sparse_index.search(question, sparse_pool) if sparse_index else []
            fused_ids = _rrf_fuse([dense_ids[:dense_pool], sparse_ids[:sparse_pool]], rrf_k=rrf_k) if sparse_ids else dense_ids
            hybrid_latency_ms = dense_latency_ms + ((time.perf_counter() - t1) * 1000.0)

            t2 = time.perf_counter()
            rerank_latency_ms = hybrid_latency_ms

            mode_to_retrieved: dict[str, list[str]] = {
                "dense": dense_ids[:max_k],
                "hybrid": fused_ids[:max_k],
            }

            if "hybrid_rerank" in requested_modes:
                rerank_candidates = fused_ids[:rerank_pool]
                reranked = sorted(
                    rerank_candidates,
                    key=lambda doc_id: _simple_rerank_score(question, doc_by_id.get(doc_id, "")),
                    reverse=True,
                )
                mode_to_retrieved["hybrid_rerank"] = reranked[:max_k]
                rerank_latency_ms = hybrid_latency_ms + ((time.perf_counter() - t2) * 1000.0)

            dense_cross_encoder_latency_ms = dense_latency_ms
            if "dense_cross_encoder" in requested_modes:
                if cross_encoder is None:
                    raise RuntimeError("CrossEncoder was not loaded")
                t3 = time.perf_counter()
                dense_ce_candidates = dense_ids[:rerank_pool]
                dense_ce_reranked = _cross_encoder_rerank(
                    query=question,
                    candidate_ids=dense_ce_candidates,
                    doc_by_id=doc_by_id,
                    cross_encoder=cross_encoder,
                    batch_size=cross_encoder_batch_size,
                )
                mode_to_retrieved["dense_cross_encoder"] = dense_ce_reranked[:max_k]
                dense_cross_encoder_latency_ms = dense_latency_ms + ((time.perf_counter() - t3) * 1000.0)

            hybrid_cross_encoder_latency_ms = hybrid_latency_ms
            if "hybrid_cross_encoder" in requested_modes:
                if cross_encoder is None:
                    raise RuntimeError("CrossEncoder was not loaded")
                t4 = time.perf_counter()
                hybrid_ce_candidates = fused_ids[:rerank_pool]
                hybrid_ce_reranked = _cross_encoder_rerank(
                    query=question,
                    candidate_ids=hybrid_ce_candidates,
                    doc_by_id=doc_by_id,
                    cross_encoder=cross_encoder,
                    batch_size=cross_encoder_batch_size,
                )
                mode_to_retrieved["hybrid_cross_encoder"] = hybrid_ce_reranked[:max_k]
                hybrid_cross_encoder_latency_ms = hybrid_latency_ms + ((time.perf_counter() - t4) * 1000.0)

            mode_to_latency_ms: dict[str, float] = {
                "dense": dense_latency_ms,
                "hybrid": hybrid_latency_ms,
                "hybrid_rerank": rerank_latency_ms,
                "dense_cross_encoder": dense_cross_encoder_latency_ms,
                "hybrid_cross_encoder": hybrid_cross_encoder_latency_ms,
            }

            for mode in requested_modes:
                retrieved_ids = mode_to_retrieved[mode]
                hit_rank: int | None = None
                for rank, chunk_id in enumerate(retrieved_ids, start=1):
                    if chunk_id == source_chunk_id:
                        hit_rank = rank
                        break

                query_result = {
                    "query_id": query_id,
                    "question": question,
                    "source_chunk_id": source_chunk_id,
                    "question_type": question_type,
                    "hit_rank": hit_rank,
                    "retrieved_ids": retrieved_ids,
                    "latency_ms": mode_to_latency_ms.get(mode),
                }
                for k in top_k:
                    query_result[f"hit_at_{k}"] = bool(hit_rank is not None and hit_rank <= k)

                by_mode_per_query[mode].append(query_result)

            succeeded_queries += 1
        except Exception as exc:
            failed_queries.append(
                {
                    "query_id": query_id,
                    "question": question,
                    "source_chunk_id": source_chunk_id,
                    "error_type": type(exc).__name__,
                    "error_message": str(exc),
                }
            )
            continue

    by_mode = {
        mode: {
            "summary": _build_summary(by_mode_per_query[mode], top_k),
            "per_query": by_mode_per_query[mode],
        }
        for mode in requested_modes
    }

    failure_rate = (len(failed_queries) / attempted_queries) if attempted_queries else 0.0

    return {
        "config": {
            "top_k": top_k,
            "modes": requested_modes,
            "dense_pool": dense_pool,
            "sparse_pool": sparse_pool,
            "rerank_pool": rerank_pool,
            "rrf_k": rrf_k,
            "cross_encoder_model": cross_encoder_model,
            "cross_encoder_batch_size": cross_encoder_batch_size,
            "cross_encoder_max_length": cross_encoder_max_length,
            "cross_encoder_trust_remote_code": cross_encoder_trust_remote_code,
        },
        "run_status": {
            "attempted_queries": attempted_queries,
            "succeeded_queries": succeeded_queries,
            "failed_queries": len(failed_queries),
            "failure_rate": failure_rate,
        },
        "failed_queries_preview": failed_queries[:10],
        "modes": by_mode,
    }


def main() -> None:
    args = parse_args()

    triples, input_summary = _load_triples(args.triples)
    if not triples:
        print(f"❌ No valid triples found in: {args.triples}")
        sys.exit(1)

    if args.max_queries and args.max_queries > 0:
        triples = triples[: args.max_queries]

    print(f"📥 Loaded triples: {len(triples)}")
    if input_summary["rows_skipped_missing_required"]:
        print(
            "⚠️  Skipped input rows missing required fields: "
            f"{input_summary['rows_skipped_missing_required']}"
        )
    print(f"🎯 Evaluating top-k: {args.top_k}")
    print(f"⚙️  Modes: {args.modes}")
    if any("cross_encoder" in mode for mode in args.modes):
        print(f"🔁 CrossEncoder reranker: {args.cross_encoder_model}")

    eval_results = evaluate_retrieval_side_by_side(
        triples=triples,
        top_k=args.top_k,
        modes=args.modes,
        dense_pool=args.dense_pool,
        sparse_pool=args.sparse_pool,
        rerank_pool=args.rerank_pool,
        rrf_k=args.rrf_k,
        cross_encoder_model=args.cross_encoder_model,
        cross_encoder_batch_size=args.cross_encoder_batch_size,
        cross_encoder_max_length=args.cross_encoder_max_length,
        cross_encoder_trust_remote_code=args.cross_encoder_trust_remote_code,
    )
    eval_results["input_summary"] = input_summary

    output_path = args.output
    if args.run_name.strip():
        safe_name = _safe_run_name(args.run_name)
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_path = DEFAULT_RESULTS_DIR / f"{safe_name}_{ts}.json"

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as fh:
        json.dump(eval_results, fh, indent=2, ensure_ascii=False)

    if args.run_name.strip():
        csv_path = DEFAULT_RESULTS_DIR / "comparison.csv"
        _append_comparison_csv(
            csv_path=csv_path,
            run_name=_safe_run_name(args.run_name),
            output_path=output_path,
            eval_results=eval_results,
        )

    print("\n════════════════════════════════════════════════════")
    for mode, payload in eval_results["modes"].items():
        summary = payload["summary"]
        print(f"\nMode: {mode}")
        print(f"Queries evaluated: {summary['n_queries']}")
        run_status = eval_results["run_status"]
        print(
            "Run status: "
            f"attempted={run_status['attempted_queries']}, "
            f"succeeded={run_status['succeeded_queries']}, "
            f"failed={run_status['failed_queries']}"
        )
        print(
            "Recall@k: "
            + ", ".join(
                f"R@{k}={summary['recall_at_k'][str(k)]:.3f}" for k in summary["top_k"]
            )
        )
        print(
            "nDCG@k: "
            + ", ".join(
                f"nDCG@{k}={summary['ndcg_at_k'][str(k)]:.3f}" for k in summary["top_k"]
            )
        )
        print(
            "Precision@k: "
            + ", ".join(
                f"P@{k}={summary['precision_at_k'][str(k)]:.3f}" for k in summary["top_k"]
            )
        )
        print(f"MRR: {summary['mrr']:.3f}")
        if summary["latency_p95_ms"] is not None:
            print(
                f"Latency p50/p95 (ms): "
                f"{summary['latency_p50_ms']:.1f}/{summary['latency_p95_ms']:.1f}"
            )
        if summary["avg_hit_rank"] is not None:
            print(f"Avg hit rank: {summary['avg_hit_rank']:.2f}")
            print(f"Median hit rank: {summary['median_hit_rank']:.2f}")
        else:
            print("Avg/median hit rank: n/a (no hits)")
    print(f"Results saved: {output_path}")
    if eval_results["failed_queries_preview"]:
        print(
            "Failed query preview saved in JSON: "
            f"{len(eval_results['failed_queries_preview'])} entries"
        )
    if args.run_name.strip():
        print(f"Comparison CSV updated: {DEFAULT_RESULTS_DIR / 'comparison.csv'}")


if __name__ == "__main__":
    main()
