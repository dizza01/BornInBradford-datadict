def _get_hf_endpoint_client(base_url: str, endpoint_mode: str) -> Any:
    token = os.getenv("HF_TOKEN", "") or os.getenv("HUGGINGFACE_TOKEN", "")
    if not token:
        raise RuntimeError(
            "HF_TOKEN not set. Export HF_TOKEN='hf_...' before running endpoint mode."
        )

    if not base_url.strip():
        raise RuntimeError("--answer-endpoint-url is required when --answer-api-mode=hf_endpoint")

    # NOTE: handler_* modes do not use huggingface_hub at all; they POST directly to the endpoint.
    hf_client = None
    if (endpoint_mode or "").strip() not in {"handler_messages", "handler_structured"}:
        try:
            from huggingface_hub import InferenceClient
        except ImportError as exc:
            raise RuntimeError(
                "huggingface_hub is required for --answer-endpoint-mode=text_generation or chat_completions. "
                "Install with: pip install huggingface_hub"
            ) from exc
        hf_client = InferenceClient(model=base_url.strip(), token=token)

    class _Wrapper:
        def __init__(self, hf_client, mode: str):
            self._hf = hf_client
            self.endpoint_mode = mode
            self.base_url = base_url.strip().rstrip("/")
            self.token = token

        
        def generate(self, prompt, temperature=0.2, max_tokens=1500, **kw):
            if self._hf is None:
                raise RuntimeError(
                    "Endpoint client was created without huggingface_hub because --answer-endpoint-mode=handler_messages. "
                    "Use handler_messages_generate() for this mode."
                )
            # Hugging Face Inference Endpoints text-generation expects a flat prompt string.
            # (Some older custom handlers accepted chat-style inputs; those should use
            # endpoint_mode=chat_completions instead.)
            inputs = str(prompt)
            return self._hf.text_generation(
                prompt=inputs,
                max_new_tokens=max_tokens,
                temperature=temperature,
                **kw,
            )

        def chat_generate(self, messages, model="", temperature=0.2, max_tokens=1500):
            # Use a direct OpenAI-compatible HTTP call to the endpoint.
            # This matches the working pattern:
            #   POST <endpoint-url>/v1/chat/completions {model, messages, ...}
            # and avoids library-specific URL composition differences.
            import urllib.request
            import urllib.error

            # Different gateways/tools treat the endpoint base URL differently:
            # - Some expect base_url="..." and path "/v1/chat/completions"
            # - Others expect base_url=".../v1" and path "/chat/completions"
            # Try both so users don't have to guess.
            base = self.base_url
            candidate_urls: list[str] = []
            if base.endswith("/v1"):
                candidate_urls.append(f"{base}/chat/completions")
                candidate_urls.append(f"{base[:-3]}/v1/chat/completions")
            else:
                candidate_urls.append(f"{base}/v1/chat/completions")
                candidate_urls.append(f"{base}/chat/completions")

            payload = {
                "messages": messages,
                "temperature": float(temperature),
                "max_tokens": int(max_tokens),
            }
            if model:
                payload["model"] = model

            body = json.dumps(payload).encode("utf-8")
            last_http_error: Exception | None = None
            raw = ""
            url = candidate_urls[0]
            for candidate in candidate_urls:
                url = candidate
                req = urllib.request.Request(
                    url=url,
                    data=body,
                    headers={
                        "Authorization": f"Bearer {self.token}",
                        "Content-Type": "application/json",
                    },
                    method="POST",
                )

                try:
                    with urllib.request.urlopen(req, timeout=120) as resp:
                        raw = resp.read().decode("utf-8", errors="replace")
                    break
                except urllib.error.HTTPError as exc:
                    err_body = (
                        exc.read().decode("utf-8", errors="replace") if hasattr(exc, "read") else ""
                    )
                    last_http_error = RuntimeError(
                        f"Client error '{exc.code} {exc.reason}' for url '{url}': {err_body}"
                    )
                    # If the route doesn't exist (404), try alternate chat route.
                    # For other HTTP errors (401/403/5xx), fail fast.
                    if int(getattr(exc, "code", 0) or 0) == 404:
                        continue
                    raise last_http_error from exc
                except urllib.error.URLError as exc:
                    raise RuntimeError(f"Endpoint request failed for url '{url}': {exc}") from exc

            if not raw and last_http_error is not None:
                tried = ", ".join(candidate_urls)
                raise RuntimeError(f"All chat routes failed (tried: {tried}). Last error: {last_http_error}")

            try:
                data = json.loads(raw)
            except json.JSONDecodeError as exc:
                raise RuntimeError(f"Invalid JSON from endpoint: {raw[:500]}") from exc

            choices = data.get("choices") or []
            if not choices:
                raise RuntimeError(f"No choices in endpoint response: {data}")
            msg = (choices[0].get("message") or {})
            content = (msg.get("content") or "")
            return str(content).strip()

        def handler_messages_generate(
            self,
            messages: list[dict[str, str]],
            temperature: float = 0.2,
            max_tokens: int = 1500,
            parameters: dict[str, Any] | None = None,
        ) -> str:
            """Call an endpoint root using the custom handler schema.

            Expected schema (as used in Colab experiments):
              POST <endpoint-base-url>
              {
                "inputs": [ {"role": "system", "content": "..."}, ... ],
                "parameters": {"max_new_tokens": ..., "temperature": ...}
              }

            Returns the "generated_text" field from the JSON response.
            """
            try:
                import requests
            except ImportError as exc:
                raise RuntimeError(
                    "The 'requests' package is required for --answer-endpoint-mode=handler_messages. "
                    "Install it with: pip install requests"
                ) from exc

            url = self.base_url
            params: dict[str, Any] = {
                "temperature": float(temperature),
                "max_new_tokens": int(max_tokens),
            }
            if isinstance(parameters, dict):
                # Allow caller overrides/additions.
                params.update(parameters)

            payload: dict[str, Any] = {
                "inputs": messages,
                "parameters": params,
            }

            resp = requests.post(
                url,
                headers={
                    "Authorization": f"Bearer {self.token}",
                    "Content-Type": "application/json",
                },
                json=payload,
                timeout=120,
            )
            if resp.status_code >= 400:
                raise RuntimeError(
                    f"Endpoint handler request failed: {resp.status_code} {resp.reason}: {resp.text[:1000]}"
                )

            try:
                data = resp.json()
            except Exception as exc:
                raise RuntimeError(f"Invalid JSON from endpoint handler: {resp.text[:1000]}") from exc

            # Most handlers return a dict with generated_text.
            if isinstance(data, dict) and isinstance(data.get("generated_text"), str):
                return str(data["generated_text"]).strip()
            # Some handlers return a list of {generated_text: ...}
            if isinstance(data, list) and data and isinstance(data[0], dict) and isinstance(data[0].get("generated_text"), str):
                return str(data[0]["generated_text"]).strip()

            raise RuntimeError(
                f"Unexpected handler response shape (no generated_text): {type(data).__name__}"
            )

        def handler_structured_generate(
            self,
            system: str,
            context: str,
            question: str,
            temperature: float = 0.2,
            max_tokens: int = 1500,
            parameters: dict[str, Any] | None = None,
        ) -> str:
            """Call an endpoint root using a structured handler schema.

                        Expected schema (matches custom handler.py patterns):
              POST <endpoint-base-url>
              {
                "inputs": {"system": "...", "context": "...", "question": "..."},
                "parameters": {"max_new_tokens": ..., "temperature": ...}
              }

            Returns the "generated_text" field from the JSON response.
            """
            try:
                import requests
            except ImportError as exc:
                raise RuntimeError(
                    "The 'requests' package is required for --answer-endpoint-mode=handler_structured. "
                    "Install it with: pip install requests"
                ) from exc

            url = self.base_url
            params: dict[str, Any] = {
                "temperature": float(temperature),
                "max_new_tokens": int(max_tokens),
            }
            if isinstance(parameters, dict):
                params.update(parameters)

            payload: dict[str, Any] = {
                "inputs": {
                    "system": str(system),
                    "context": str(context),
                    "question": str(question),
                },
                "parameters": params,
            }

            resp = requests.post(
                url,
                headers={
                    "Authorization": f"Bearer {self.token}",
                    "Content-Type": "application/json",
                },
                json=payload,
                timeout=120,
            )
            if resp.status_code >= 400:
                raise RuntimeError(
                    f"Endpoint handler request failed: {resp.status_code} {resp.reason}: {resp.text[:1000]}"
                )

            try:
                data = resp.json()
            except Exception as exc:
                raise RuntimeError(
                    f"Invalid JSON from endpoint handler: {resp.text[:1000]}"
                ) from exc

            if isinstance(data, dict) and isinstance(data.get("generated_text"), str):
                return str(data["generated_text"]).strip()
            if (
                isinstance(data, list)
                and data
                and isinstance(data[0], dict)
                and isinstance(data[0].get("generated_text"), str)
            ):
                return str(data[0]["generated_text"]).strip()

            raise RuntimeError(
                f"Unexpected handler response shape (no generated_text): {type(data).__name__}"
            )

    return _Wrapper(hf_client, endpoint_mode)


def _generate_rag_answer(
    question: str,
    context: str,
    llm_client: Any,
    model: str,
    max_tokens: int,
    allow_endpoint_chat_fallback: bool = False,
    # handler_parameters is forwarded verbatim into the handler payload's `parameters`.
    handler_parameters: dict[str, Any] | None = None,
    temperature: float = 0.2,
) -> str:
    # If llm_client has 'generate', use standard HF endpoint; else, use chat.completions.create
    if hasattr(llm_client, "generate"):
        endpoint_mode = getattr(llm_client, "endpoint_mode", "text_generation")

        def _is_chat_404(exc: Exception) -> bool:
            msg = str(exc)
            return (
                "404" in msg
                and "chat/completions" in msg
                and "Not Found" in msg
            )

        def _is_model_not_found_404(exc: Exception) -> bool:
            # OpenAI-compatible servers often return a 404 for an unknown model name.
            # Those errors should not be reported as a missing route.
            msg = str(exc).lower()
            return (
                "404" in msg
                and "model" in msg
                and (
                    "does not exist" in msg
                    or "not found" in msg
                    or "model_not_found" in msg
                )
            )

        if endpoint_mode in {"chat_completions", "handler_messages", "handler_structured"}:
            messages = [
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": (
                        f"Retrieved knowledge base context:\n\n{context}\n\n"
                        f"---\n\nResearcher question: {question}"
                    ),
                },
            ]

            # handler_structured is used when the endpoint handler requires a structured `inputs` dict
            # rather than a chat messages list.
            if endpoint_mode == "handler_structured":
                max_attempts = 6
                base_delay = 1.0
                for attempt in range(1, max_attempts + 1):
                    try:
                        answer = llm_client.handler_structured_generate(
                            system=SYSTEM_PROMPT,
                            context=context,
                            question=question,
                            temperature=float(temperature),
                            max_tokens=max_tokens,
                            parameters=handler_parameters,
                        )
                        return _strip_filler(answer).strip()
                    except Exception as exc:
                        msg = str(exc)
                        if "503" in msg or "Service Unavailable" in msg:
                            if attempt < max_attempts:
                                wait = base_delay * (2 ** (attempt - 1))
                                print(
                                    f"[WARN] 503 Service Unavailable, retrying in {wait:.1f}s (attempt {attempt}/{max_attempts})..."
                                )
                                time.sleep(wait)
                                continue
                        raise

            if endpoint_mode == "handler_messages":
                # The endpoint is expected to support a custom handler schema at the root.
                # This is the only mode that matches the Colab payload:
                #   POST <base_url> {"inputs": messages, "parameters": {...}}
                max_attempts = 6
                base_delay = 1.0
                for attempt in range(1, max_attempts + 1):
                    try:
                        answer = llm_client.handler_messages_generate(
                            messages=messages,
                            temperature=float(temperature),
                            max_tokens=max_tokens,
                            parameters=handler_parameters,
                        )
                        return _strip_filler(answer).strip()
                    except Exception as exc:
                        msg = str(exc)
                        if "503" in msg or "Service Unavailable" in msg:
                            if attempt < max_attempts:
                                wait = base_delay * (2 ** (attempt - 1))
                                print(
                                    f"[WARN] 503 Service Unavailable, retrying in {wait:.1f}s (attempt {attempt}/{max_attempts})..."
                                )
                                time.sleep(wait)
                                continue
                        raise

            max_attempts = 6
            base_delay = 1.0
            for attempt in range(1, max_attempts + 1):
                try:
                    answer = llm_client.chat_generate(
                        messages=messages,
                        model=model,
                        temperature=float(temperature),
                        max_tokens=max_tokens,
                    )
                    return _strip_filler(answer).strip()
                except Exception as exc:
                    msg = str(exc)
                    if _is_model_not_found_404(exc):
                        raise RuntimeError(
                            "Endpoint returned 404 for the requested model name. "
                            "Fix: query the endpoint's served model id (try GET <endpoint>/v1/models) and pass it via "
                            "--answer-endpoint-model. If your endpoint does not require a model field, set --answer-model to a "
                            "run label without a '/', so the script omits the model parameter. "
                            f"Raw error: {exc}"
                        ) from exc
                    if _is_chat_404(exc):
                        if not allow_endpoint_chat_fallback:
                            raise RuntimeError(
                                "Endpoint chat routes returned 404 (Not Found). "
                                "This script tries both '/v1/chat/completions' and '/chat/completions' automatically. "
                                "If you're using a vLLM OpenAI server, a 404 can also mean the *model name* was not found; "
                                "in that case, pass the served id via --answer-endpoint-model (discover with GET <endpoint>/v1/models). "
                                "Otherwise, use --allow-endpoint-chat-fallback to permit text_generation fallback. "
                                f"Raw error: {exc}"
                            ) from exc

                        print(
                            "[WARN] Endpoint does not support /v1/chat/completions. "
                            "Falling back to text_generation for this run (--allow-endpoint-chat-fallback enabled)."
                        )
                        llm_client.endpoint_mode = "text_generation"
                        endpoint_mode = "text_generation"
                        break
                    if "503" in msg or "Service Unavailable" in msg:
                        if attempt < max_attempts:
                            wait = base_delay * (2 ** (attempt - 1))
                            print(f"[WARN] 503 Service Unavailable, retrying in {wait:.1f}s (attempt {attempt}/{max_attempts})...")
                            time.sleep(wait)
                            continue
                    raise

        def _is_not_found_404(exc: Exception) -> bool:
            msg = str(exc)
            return (
                "404" in msg
                and (
                    "Not Found" in msg
                    or "404 Not Found" in msg
                    or "Client error '404" in msg
                )
            )

        # Standard HF endpoint: build a single prompt string
        prompt = f"{SYSTEM_PROMPT}\n\nRetrieved knowledge base context:\n\n{context}\n\n---\n\nResearcher question: {question}"
        max_attempts = 6  # up to ~31s total wait
        base_delay = 1.0
        for attempt in range(1, max_attempts + 1):
            try:
                response = llm_client.generate(
                    prompt=prompt,
                    temperature=float(temperature),
                    max_tokens=max_tokens,
                )
                answer = _normalize_endpoint_generation_response(response)
                # Some endpoints return the prompt + answer, so try to strip the prompt if present
                if answer.startswith(prompt):
                    answer = answer[len(prompt):].strip()
                return _strip_filler(answer).strip()
            except Exception as exc:
                # Some endpoints are OpenAI-compatible and only implement /v1/chat/completions.
                # In that case, text_generation calls can 404 at the base URL.
                if _is_not_found_404(exc):
                    print(
                        "[WARN] Endpoint returned 404 for text_generation; "
                        "retrying via /v1/chat/completions (OpenAI-compatible endpoint detected)."
                    )
                    # Switch the client to chat mode for the remainder of the run.
                    # This avoids a 404 round-trip per query on chat-only endpoints.
                    try:
                        llm_client.endpoint_mode = "chat_completions"
                    except Exception:
                        pass
                    messages = [
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {
                            "role": "user",
                            "content": (
                                f"Retrieved knowledge base context:\n\n{context}\n\n"
                                f"---\n\nResearcher question: {question}"
                            ),
                        },
                    ]
                    answer = llm_client.chat_generate(
                        messages=messages,
                        model=model,
                        temperature=float(temperature),
                        max_tokens=max_tokens,
                    )
                    return _strip_filler(answer).strip()

                # Retry on 503 errors (cold start)
                msg = str(exc)
                if "503" in msg or "Service Unavailable" in msg:
                    if attempt < max_attempts:
                        wait = base_delay * (2 ** (attempt - 1))
                        print(f"[WARN] 503 Service Unavailable, retrying in {wait:.1f}s (attempt {attempt}/{max_attempts})...")
                        time.sleep(wait)
                        continue
                raise
    else:
        # OpenAI-style client
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": (
                    f"Retrieved knowledge base context:\n\n{context}\n\n"
                    f"---\n\nResearcher question: {question}"
                ),
            },
        ]
        response = llm_client.chat.completions.create(
            model=model,
            messages=messages,
            temperature=float(temperature),
            max_tokens=max_tokens,
        )
        answer = response.choices[0].message.content or ""
        return _strip_filler(answer).strip()


def _retrieve_context_dense(question: str, client: Any, n_results: int) -> str:
    """Dense-only paper retrieval, keeping variable/table retrieval unchanged.

    This isolates paper retrieval mode changes while preserving the rest of the
    context structure used by the baseline pipeline.
    """
    n_results = max(1, int(n_results))
    context_parts: list[str] = []

    # Papers (dense only, PDF full-text)
    try:
        papers_col = client.get_collection("bib_papers")
        dense_results = papers_col.query(
            query_texts=[question],
            n_results=n_results,
            where={"source": "pdf_fulltext"},
            include=["documents", "metadatas"],
        )
        docs = (dense_results.get("documents") or [[]])[0] or []
        metas = (dense_results.get("metadatas") or [[]])[0] or []

        if any(docs):
            context_parts.append("## Relevant Published Papers\n")
            for doc, meta in zip(docs, metas):
                if not doc:
                    continue
                meta = meta or {}
                context_parts.append(
                    f"**{meta.get('title','')[:120]}** "
                    f"({meta.get('year','')}) — {meta.get('authors','')[:80]}\n"
                    f"{doc[doc.find('Abstract:'):doc.find('Abstract:')+600] if 'Abstract:' in doc else doc[:400]}\n"
                )
    except Exception as exc:
        context_parts.append(f"[Papers collection unavailable: {exc}]\n")

    # Variables (same as baseline)
    try:
        vars_col = client.get_collection("bib_variables")
        results = vars_col.query(
            query_texts=[question],
            n_results=n_results * 2,
            include=["documents", "metadatas"],
        )
        docs = results["documents"][0]
        metas = results["metadatas"][0]
        if docs:
            context_parts.append("\n## Relevant Variables\n")
            for doc, meta in zip(docs, metas):
                meta = meta or {}
                if "Variable ID:" not in doc and meta.get("variable_id"):
                    doc = f"Variable ID: {meta.get('variable_id')}\n{doc}"
                context_parts.append(f"```\n{doc}\n```\n")
    except Exception as exc:
        context_parts.append(f"[Variables collection unavailable: {exc}]\n")

    # Tables (same as baseline)
    try:
        tables_col = client.get_collection("bib_tables")
        results = tables_col.query(query_texts=[question], n_results=n_results)
        docs = results["documents"][0]
        if docs:
            context_parts.append("\n## Relevant Tables\n")
            for doc in docs:
                context_parts.append(f"```\n{doc}\n```\n")
    except Exception as exc:
        context_parts.append(f"[Tables collection unavailable: {exc}]\n")

    return "\n".join(context_parts)


def _retrieve_context_for_eval(
    question: str,
    client: Any,
    retrieval_mode: str,
    dense_top_k: int,
) -> str:
    mode = (retrieval_mode or "default").strip().lower()
    if mode == "dense":
        return _retrieve_context_dense(question=question, client=client, n_results=dense_top_k)
    return retrieve_context(question, client)


def _judge_faithfulness(
    question: str,
    context: str,
    answer: str,
    judge_client: Any,
    judge_model: str,
    max_tokens: int,
    retries: int,
    retry_delay: float,
) -> dict[str, Any]:
    user_prompt = (
        "Evaluate faithfulness of the answer against retrieved context.\n\n"
        f"Question:\n{question}\n\n"
        f"Retrieved context:\n{context}\n\n"
        f"Answer:\n{answer}"
    )

    raw = ""
    parsed: dict[str, Any] | None = None
    last_exc: Exception | None = None
    max_attempts = max(1, retries + 1)

    for attempt in range(1, max_attempts + 1):
        try:
            messages = [
                {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ]
            if attempt > 1 and raw:
                messages.extend(
                    [
                        {"role": "assistant", "content": raw},
                        {
                            "role": "user",
                            "content": (
                                "Your previous response could not be parsed. "
                                "Return ONLY the tab-delimited format with BEGIN_JUDGE/END_JUDGE markers, "
                                "literal tabs between fields, and at most 8 CLAIM rows."
                            ),
                        },
                    ]
                )

            response = judge_client.chat.completions.create(
                model=judge_model,
                messages=messages,
                temperature=0.0,
                max_tokens=max_tokens,
            )

            raw = response.choices[0].message.content or ""
            parsed = _parse_judge_response(raw)
            break
        except Exception as exc:
            last_exc = exc
            if attempt < max_attempts:
                time.sleep(max(0.0, retry_delay) * attempt)
                continue
            raise RuntimeError(
                f"Judge parsing/call failed after {max_attempts} attempts for model {judge_model}: {exc}"
            ) from exc

    if parsed is None:
        raise RuntimeError(
            f"Judge parsing/call failed for model {judge_model}: {last_exc}"
        )

    claims = parsed.get("claims", [])
    if not isinstance(claims, list):
        claims = []

    # Defensive check: some judge models will "answer from context" even when the Answer is gibberish.
    # We require that extracted claims be literal substrings of the Answer (whitespace/case-normalized).
    answer_norm = _normalize_text(answer)
    invalid_claims = 0

    normalized_claims: list[dict[str, str]] = []
    supported = 0
    contradicted = 0
    not_found = 0
    unclear = 0

    for claim in claims:
        if not isinstance(claim, dict):
            continue
        claim_text = str(claim.get("claim", "")).strip()
        verdict = str(claim.get("verdict", "")).strip().lower()
        evidence = str(claim.get("evidence", "")).strip()
        if not claim_text:
            continue

        # Enforce that the claim is literally present in the answer.
        claim_norm = _normalize_text(claim_text)
        if claim_norm and answer_norm and claim_norm not in answer_norm:
            invalid_claims += 1
            # Treat as unclear and omit evidence to avoid leaking context-derived content.
            verdict = "unclear"
            evidence = ""

        if verdict not in {"supported", "contradicted", "not_found", "unclear"}:
            verdict = "unclear"

        if verdict == "supported":
            supported += 1
        elif verdict == "contradicted":
            contradicted += 1
        elif verdict == "not_found":
            not_found += 1
        else:
            unclear += 1

        normalized_claims.append(
            {
                "claim": claim_text,
                "verdict": verdict,
                "evidence": evidence,
            }
        )

    # Faithfulness definition:
    # - faithful = explicit abstention with 0 claims OR at least one supported claim and no contradicted/not_found.
    # - unclear claims do not alone make an answer unfaithful, but they contribute to "risky=True".
    # Empty model outputs are handled upstream and never reach this point.
    total_claims = len(normalized_claims)
    has_supported = supported > 0
    has_bad = (contradicted + not_found) > 0

    is_abstention = _is_explicit_abstention(answer)

    if total_claims == 0:
        # Zero claims, but we know the answer was non-empty (empty answers are handled upstream).
        # Only treat this as faithful if the answer explicitly abstains.
        faithful = bool(is_abstention)
    else:
        # At least one supported claim, and no contradicted/not_found claims.
        faithful = bool(has_supported and not has_bad)

    # Define a "risky" flag: any contradicted / not_found / unclear claims.
    # If we detected judge-invented claims, also mark as risky.
    risky = bool((contradicted + not_found + unclear) > 0 or invalid_claims > 0)

    return {
        "claims": normalized_claims,
        "counts": {
            "total": total_claims,
            "supported": supported,
            "contradicted": contradicted,
            "not_found": not_found,
            "unclear": unclear,
            "invalid_claims": invalid_claims,
        },
        "overall": {
            "faithful": faithful,
            "risky": risky,
            "notes": str((parsed.get("overall") or {}).get("notes", "")).strip(),
        },
        "raw_judge_response": raw,
    }


def _safe_div(num: float, den: float) -> float:
    return (num / den) if den else 0.0


def _normalize_text(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").strip().lower())


_ABSTAIN_PATTERNS = [
    r"\bnot enough information\b",
    r"\binsufficient information\b",
    r"\bcontext does not (?:contain|provide|include|specify)\b",
    r"\bprovided context does not\b",
    r"\bcannot answer\b",
    r"\bcan\s*'?t answer\b",
    r"\bunable to answer\b",
    r"\bunknown from the context\b",
    r"\bnot specified in the context\b",
]


def _is_explicit_abstention(answer: str) -> bool:
    text = _normalize_text(answer)
    if not text:
        return False
    return any(re.search(pat, text) for pat in _ABSTAIN_PATTERNS)


def _looks_like_gibberish(answer: str) -> bool:
    """Heuristic detector for degenerate/failed generations.

    Intentionally conservative: avoids flagging short answers, numeric-only answers,
    or normal prose. Designed to catch repetitive junk like '###\nRetD\nD\n1...'.
    """
    raw = (answer or "").strip()
    if not raw:
        return False

    # If the model is explicitly abstaining, that's not gibberish.
    if _is_explicit_abstention(raw):
        return False

    # Very short outputs are handled elsewhere (empty) or treated as low-quality but not gibberish.
    if len(raw) < 24:
        return False

    # If it's mostly hashes/markup lines, it's likely a failed decode.
    lines = [ln.strip() for ln in raw.splitlines() if ln.strip()]
    if lines:
        hashy = sum(1 for ln in lines if ln.startswith("###") or ln == "###")
        if (hashy / max(1, len(lines))) > 0.60 and len(lines) >= 6:
            return True

        # Repeated identical short lines (e.g. lots of 'RetD' or 'D')
        short_lines = [ln for ln in lines if len(ln) <= 6]
        if len(short_lines) >= 12:
            most_common = max((short_lines.count(ln) for ln in set(short_lines)), default=0)
            if _safe_div(most_common, len(short_lines)) >= 0.50:
                return True

    chars = raw
    alnum = sum(1 for c in chars if c.isalnum())
    letters = sum(1 for c in chars if c.isalpha())
    non_ws = sum(1 for c in chars if not c.isspace())

    # Extremely low alphabetic content is suspect unless the answer is a clear numeric table.
    alpha_ratio = _safe_div(letters, max(1, non_ws))
    if alpha_ratio < 0.10 and len(raw) > 80:
        return True

    # Token repetition / low diversity.
    toks = _simple_tokens(raw)
    if len(toks) >= 30:
        uniq_ratio = _safe_div(len(set(toks)), len(toks))
        if uniq_ratio < 0.25:
            return True
        from collections import Counter

        top_freq = Counter(toks).most_common(1)[0][1]
        if _safe_div(top_freq, len(toks)) > 0.40:
            return True

    # Mostly non-alphanumeric noise.
    alnum_ratio = _safe_div(alnum, max(1, non_ws))
    if alnum_ratio < 0.35 and len(raw) > 120:
        return True

    return False


def _simple_tokens(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+", _normalize_text(text))


def _estimate_token_count(text: str) -> int:
    return len(_simple_tokens(text))


def _token_f1(pred: str, gold: str) -> float:
    pred_tokens = _simple_tokens(pred)
    gold_tokens = _simple_tokens(gold)
    if not pred_tokens or not gold_tokens:
        return 0.0

    pred_counts: dict[str, int] = {}
    for tok in pred_tokens:
        pred_counts[tok] = pred_counts.get(tok, 0) + 1

    gold_counts: dict[str, int] = {}
    for tok in gold_tokens:
        gold_counts[tok] = gold_counts.get(tok, 0) + 1

    overlap = 0
    for tok, c in pred_counts.items():
        overlap += min(c, gold_counts.get(tok, 0))

    precision = overlap / len(pred_tokens)
    recall = overlap / len(gold_tokens)
    return _safe_div(2 * precision * recall, precision + recall)


def _answer_relevance_score(question: str, answer: str) -> float:
    q = set(_simple_tokens(question))
    a = set(_simple_tokens(answer))
    if not q or not a:
        return 0.0
    overlap = len(q & a)
    return _safe_div(overlap, len(q))


def _completeness_score(answer: str, reference_answer: str) -> float:
    ref_tokens = _simple_tokens(reference_answer)
    ans_tokens = set(_simple_tokens(answer))
    if not ref_tokens:
        return 0.0
    covered = sum(1 for tok in ref_tokens if tok in ans_tokens)
    return _safe_div(covered, len(ref_tokens))


def _conciseness_score(answer: str, reference_answer: str) -> float:
    ans_len = max(1, _estimate_token_count(answer))
    ref_len = max(1, _estimate_token_count(reference_answer))
    ratio = ans_len / ref_len
    return math.exp(-abs(math.log(ratio)))


def _is_exact_match(answer: str, reference_answer: str) -> bool:
    return _normalize_text(answer) == _normalize_text(reference_answer)


def _summarize_generation_quality(per_query_rows: list[dict[str, Any]]) -> dict[str, Any]:
    n = len(per_query_rows)
    if n == 0:
        return {
            "n_queries": 0,
            "answer_relevance": 0.0,
            "completeness": 0.0,
            "conciseness": 0.0,
            "answer_correctness_token_f1": 0.0,
            "answer_correctness_exact_match_rate": 0.0,
            "latency_total_p50_ms": 0.0,
            "latency_total_p95_ms": 0.0,
            "latency_retrieval_avg_ms": 0.0,
            "latency_answer_avg_ms": 0.0,
            "avg_retrieved_tokens": 0.0,
            "avg_answer_tokens": 0.0,
            "answer_tokens_per_retrieved_token": 0.0,
        }

    relevance_vals = [float(r.get("answer_relevance", 0.0)) for r in per_query_rows]
    completeness_vals = [float(r.get("completeness", 0.0)) for r in per_query_rows]
    conciseness_vals = [float(r.get("conciseness", 0.0)) for r in per_query_rows]
    correctness_f1_vals = [float(r.get("answer_correctness_token_f1", 0.0)) for r in per_query_rows]
    exact_match_vals = [1.0 if bool(r.get("answer_exact_match", False)) else 0.0 for r in per_query_rows]

    total_latencies = sorted(float(r.get("latency_total_ms", 0.0)) for r in per_query_rows)
    retrieval_avg = _safe_div(sum(float(r.get("latency_retrieval_ms", 0.0)) for r in per_query_rows), n)
    answer_avg = _safe_div(sum(float(r.get("latency_answer_ms", 0.0)) for r in per_query_rows), n)

    avg_retrieved_tokens = _safe_div(sum(int(r.get("retrieved_tokens", 0)) for r in per_query_rows), n)
    avg_answer_tokens = _safe_div(sum(int(r.get("answer_tokens", 0)) for r in per_query_rows), n)
    token_eff = _safe_div(avg_answer_tokens, avg_retrieved_tokens)

    p50_idx = max(0, min(len(total_latencies) - 1, math.ceil(0.50 * len(total_latencies)) - 1))
    p95_idx = max(0, min(len(total_latencies) - 1, math.ceil(0.95 * len(total_latencies)) - 1))

    return {
        "n_queries": n,
        "answer_relevance": _safe_div(sum(relevance_vals), n),
        "completeness": _safe_div(sum(completeness_vals), n),
        "conciseness": _safe_div(sum(conciseness_vals), n),
        "answer_correctness_token_f1": _safe_div(sum(correctness_f1_vals), n),
        "answer_correctness_exact_match_rate": _safe_div(sum(exact_match_vals), n),
        "latency_total_p50_ms": total_latencies[p50_idx],
        "latency_total_p95_ms": total_latencies[p95_idx],
        "latency_retrieval_avg_ms": retrieval_avg,
        "latency_answer_avg_ms": answer_avg,
        "avg_retrieved_tokens": avg_retrieved_tokens,
        "avg_answer_tokens": avg_answer_tokens,
        "answer_tokens_per_retrieved_token": token_eff,
    }


def _summarize(judgments: list[dict[str, Any]]) -> dict[str, Any]:
    n_queries = len(judgments)

    total_claims = sum(j["counts"]["total"] for j in judgments)
    total_supported = sum(j["counts"]["supported"] for j in judgments)
    total_contradicted = sum(j["counts"]["contradicted"] for j in judgments)
    total_not_found = sum(j["counts"]["not_found"] for j in judgments)
    total_unclear = sum(j["counts"]["unclear"] for j in judgments)
    total_unfaithful = total_contradicted + total_not_found

    faithful_queries = sum(1 for j in judgments if j["overall"]["faithful"])
    contradicted_queries = sum(1 for j in judgments if j["counts"]["contradicted"] > 0)
    not_found_queries = sum(1 for j in judgments if j["counts"]["not_found"] > 0)
    unfaithful_queries = sum(
        1
        for j in judgments
        if (j["counts"]["contradicted"] + j["counts"]["not_found"]) > 0
    )
    # Risk is orthogonal to faithfulness: "unclear" (and any unfaithful) claims mark the answer as risky.
    risky_queries = sum(
        1
        for j in judgments
        if bool((j.get("overall") or {}).get("risky", False))
    )

    contradiction_weighted_hallucination = _safe_div(
        (2.0 * total_contradicted) + total_not_found,
        total_claims,
    )

    return {
        "n_queries": n_queries,
        "total_claims": total_claims,
        "supported_claims": total_supported,
        "contradicted_claims": total_contradicted,
        "not_found_claims": total_not_found,
        "unfaithful_claims": total_unfaithful,
        "unclear_claims": total_unclear,
        "claim_support_rate": _safe_div(total_supported, total_claims),
        "contradicted_claim_rate": _safe_div(total_contradicted, total_claims),
        "not_found_claim_rate": _safe_div(total_not_found, total_claims),
        "unfaithful_claim_rate": _safe_div(total_unfaithful, total_claims),
        "contradiction_weighted_hallucination": contradiction_weighted_hallucination,
        "query_faithfulness_rate": _safe_div(faithful_queries, n_queries),
        "contradicted_query_rate": _safe_div(contradicted_queries, n_queries),
        "not_found_query_rate": _safe_div(not_found_queries, n_queries),
        "unfaithful_query_rate": _safe_div(unfaithful_queries, n_queries),
        "risky_queries": risky_queries,
        "risky_query_rate": _safe_div(risky_queries, n_queries),
        "avg_claims_per_answer": _safe_div(total_claims, n_queries),
        "avg_unfaithful_claims_per_answer": _safe_div(total_unfaithful, n_queries),
    }


def _judge_agreement(
    external_judgments: list[dict[str, Any]],
    qwen_judgments: list[dict[str, Any]],
) -> dict[str, Any]:
    n = min(len(external_judgments), len(qwen_judgments))
    if n == 0:
        return {
            "n_queries": 0,
            "faithful_label_agreement": 0.0,
            "unfaithful_presence_agreement": 0.0,
        }

    faithful_same = 0
    unfaithful_same = 0
    for ext, qwn in zip(external_judgments, qwen_judgments):
        if bool(ext["overall"]["faithful"]) == bool(qwn["overall"]["faithful"]):
            faithful_same += 1

        ext_has_unfaithful = (ext["counts"]["contradicted"] + ext["counts"]["not_found"]) > 0
        qwn_has_unfaithful = (qwn["counts"]["contradicted"] + qwn["counts"]["not_found"]) > 0
        if ext_has_unfaithful == qwn_has_unfaithful:
            unfaithful_same += 1

    return {
        "n_queries": n,
        "faithful_label_agreement": faithful_same / n,
        "unfaithful_presence_agreement": unfaithful_same / n,
    }


def _safe_run_name(run_name: str) -> str:
    safe = re.sub(r"[^a-zA-Z0-9._-]+", "_", run_name.strip())
    return safe.strip("_") or "run"


