def main() -> None:
    args = parse_args()

    _validate_models(
        answer_model=args.answer_model,
        external_judge_model=args.external_judge_model,
        qwen_judge_model=args.qwen_judge_model,
    )

    triples = _load_questions(args.triples)
    if not triples:
        print(f"❌ No valid questions found in: {args.triples}")
        sys.exit(1)

    if args.max_queries and args.max_queries > 0:
        triples = triples[: args.max_queries]

    def _looks_like_repo_id(name: str) -> bool:
        return "/" in (name or "")

    rag_client = None
    answer_model_for_call = args.answer_model
    if args.answer_api_mode == "hf_endpoint":
        rag_client = _get_hf_endpoint_client(args.answer_endpoint_url, args.answer_endpoint_mode)
        endpoint_model = args.answer_endpoint_model.strip()
        # For OpenAI-compatible endpoints (/v1/chat/completions), the `model` field is often optional,
        # and passing a local run label like "qwen3-6-27b-pks" will cause a 404 "model does not exist".
        # Only send a model name if the user explicitly provided --answer-endpoint-model, or if the
        # --answer-model looks like a real hub ID (org/name).
        if endpoint_model:
            answer_model_for_call = endpoint_model
        elif _looks_like_repo_id(args.answer_model):
            answer_model_for_call = args.answer_model
        else:
            answer_model_for_call = ""
    else:
        rag_client = _get_hf_client(args.answer_model)

    ext_judge_client = _get_hf_client(args.external_judge_model)
    qwen_judge_client = _get_hf_client(args.qwen_judge_model)

    if not rag_client or not ext_judge_client or not qwen_judge_client:
        sys.exit(1)

    chroma_client = get_chroma_client()

    print(f"📥 Loaded questions: {len(triples)}")
    print(f"🔎 Retrieval mode: {args.retrieval_mode}")
    print(f"🧭 Context format: {args.context_format}")
    print(f"🤖 Answer model: {args.answer_model}")
    print(f"🤖 Answer API mode: {args.answer_api_mode}")
    if args.answer_api_mode == "hf_endpoint":
        print(f"🌐 Answer endpoint: {args.answer_endpoint_url}")
        print(f"🧩 Endpoint inference mode: {args.answer_endpoint_mode}")
        print(f"🔖 Endpoint model arg: {answer_model_for_call}")
    print(f"⚖️  Primary judge (external): {args.external_judge_model}")
    print(f"🧪 Sensitivity judge (Qwen): {args.qwen_judge_model}")

    # Parameters forwarded to custom endpoint handlers (handler_* modes).
    #
    # If you run with:
    #   --answer-endpoint-mode handler_messages
    #   or
    #   --answer-endpoint-mode handler_structured
    # these values become the `parameters` dict in the POST body.
    # Note: some handlers may ignore/cap certain values (e.g., max_new_tokens).
    answer_handler_parameters: dict[str, Any] = {
        "use_system_role": bool(args.answer_endpoint_use_system_role),
        "do_sample": bool(args.answer_do_sample),
        "top_p": float(args.answer_top_p),
        "repetition_penalty": float(args.answer_repetition_penalty),
        "no_repeat_ngram_size": int(args.answer_no_repeat_ngram_size),
        "max_input_tokens": int(args.answer_max_input_tokens),
        "debug": bool(args.answer_endpoint_debug),
    }

    per_query: list[dict[str, Any]] = []
    external_judgments: list[dict[str, Any]] = []
    qwen_judgments: list[dict[str, Any]] = []
    failed_queries: list[dict[str, str]] = []
    attempted_queries = len(triples)

    for idx, triple in enumerate(triples, start=1):
        question = str(triple.get("question", "")).strip()
        query_id = str(triple.get("query_id", f"q_{idx}"))
        source_chunk_id = str(triple.get("source_chunk_id", "")).strip()

        if not question:
            continue

        is_empty_answer = False
        is_gibberish_answer = False
        try:
            t_retrieval_start = time.perf_counter()
            raw_context = _retrieve_context_for_eval(
                question=question,
                client=chroma_client,
                retrieval_mode=args.retrieval_mode,
                dense_top_k=args.dense_top_k,
            )
            if args.context_format == "question_anchors":
                answer_context = format_context_with_question_anchors(
                    question=question,
                    context=raw_context,
                )
            else:
                answer_context = raw_context
            retrieval_ms = (time.perf_counter() - t_retrieval_start) * 1000.0

            t_answer_start = time.perf_counter()
            answer = _generate_rag_answer(
                question=question,
                context=answer_context,
                llm_client=rag_client,
                model=answer_model_for_call,
                max_tokens=args.answer_max_tokens,
                allow_endpoint_chat_fallback=args.allow_endpoint_chat_fallback,
                handler_parameters=answer_handler_parameters,
                temperature=float(args.answer_temperature),
            )
            answer_ms = (time.perf_counter() - t_answer_start) * 1000.0
            # Treat truly empty model outputs as explicit failures.
            # These are NOT judged (to avoid being mis-scored as "faithful abstentions").
            is_empty_answer = (not answer or not str(answer).strip())
            is_gibberish_answer = (not is_empty_answer) and _looks_like_gibberish(str(answer))

            ext_judge_ms = 0.0
            qwen_judge_ms = 0.0

            if is_empty_answer or is_gibberish_answer:
                # Minimal judgment payload (keeps downstream JSON structure compatible).
                failure_note = "failed_empty_output" if is_empty_answer else "failed_gibberish_output"
                ext = {
                    "claims": [],
                    "counts": {
                        "total": 0,
                        "supported": 0,
                        "contradicted": 0,
                        "not_found": 0,
                        "unclear": 0,
                        "invalid_claims": 0,
                    },
                    "overall": {
                        "faithful": False,
                        "risky": True,
                        "notes": failure_note,
                    },
                    "raw_judge_response": "",
                }
                # Mirror the same semantics for the Qwen judge output.
                qwn = {
                    **ext,
                    "claims": list(ext["claims"]),
                    "counts": dict(ext["counts"]),
                    "overall": dict(ext["overall"]),
                }
            else:
                t_ext_start = time.perf_counter()
                ext = _judge_faithfulness(
                    question=question,
                    context=raw_context,
                    answer=answer,
                    judge_client=ext_judge_client,
                    judge_model=args.external_judge_model,
                    max_tokens=args.judge_max_tokens,
                    retries=args.judge_retries,
                    retry_delay=args.judge_retry_delay,
                )
                ext_judge_ms = (time.perf_counter() - t_ext_start) * 1000.0
                time.sleep(args.sleep_seconds)

                t_qwn_start = time.perf_counter()
                qwn = _judge_faithfulness(
                    question=question,
                    context=raw_context,
                    answer=answer,
                    judge_client=qwen_judge_client,
                    judge_model=args.qwen_judge_model,
                    max_tokens=args.judge_max_tokens,
                    retries=args.judge_retries,
                    retry_delay=args.judge_retry_delay,
                )
                qwen_judge_ms = (time.perf_counter() - t_qwn_start) * 1000.0
                time.sleep(args.sleep_seconds)

        except Exception as exc:
            err_msg = str(exc)
            if "Endpoint does not support /v1/chat/completions (404)" in err_msg:
                print("\n❌ Endpoint chat route unavailable: aborting strict chat run.")
                print(err_msg)
                sys.exit(2)

            print(f"⚠️  {idx:>3}/{len(triples)} failed ({query_id}): {exc}")
            failed_queries.append(
                {
                    "query_id": query_id,
                    "question": question,
                    "error": str(exc),
                }
            )
            continue

        external_judgments.append(ext)
        qwen_judgments.append(qwn)

        reference_answer = str(triple.get("answer", "")).strip()
        answer_relevance = _answer_relevance_score(question=question, answer=answer)
        completeness = _completeness_score(answer=answer, reference_answer=reference_answer)
        conciseness = _conciseness_score(answer=answer, reference_answer=reference_answer)
        correctness_f1 = _token_f1(pred=answer, gold=reference_answer)
        answer_exact_match = _is_exact_match(answer=answer, reference_answer=reference_answer)

        retrieved_tokens = _estimate_token_count(answer_context)
        raw_retrieved_tokens = _estimate_token_count(raw_context)
        answer_tokens = _estimate_token_count(answer)
        total_ms = retrieval_ms + answer_ms + ext_judge_ms + qwen_judge_ms

        result = {
            "query_id": query_id,
            "question": question,
            "reference_answer": reference_answer,
            "source_chunk_id": source_chunk_id,
            "rag_answer": answer,
            "answer_relevance": answer_relevance,
            "completeness": completeness,
            "conciseness": conciseness,
            "answer_correctness_token_f1": correctness_f1,
            "answer_exact_match": answer_exact_match,
            "retrieved_tokens": retrieved_tokens,
            "raw_retrieved_tokens": raw_retrieved_tokens,
            "answer_tokens": answer_tokens,
            "latency_retrieval_ms": retrieval_ms,
            "latency_answer_ms": answer_ms,
            "latency_external_judge_ms": ext_judge_ms,
            "latency_qwen_judge_ms": qwen_judge_ms,
            "latency_total_ms": total_ms,
            "judgments": {
                "external": ext,
                "qwen": qwn,
            },
        }
        if is_empty_answer:
            # Per-query provenance: indicates the "decision" came from empty-output handling.
            result["classifier_decision_source_external"] = "empty_answer"
            result["classifier_decision_source_qwen"] = "empty_answer"
        elif is_gibberish_answer:
            # Per-query provenance: indicates the "decision" came from degenerate-output handling.
            result["classifier_decision_source_external"] = "gibberish_answer"
            result["classifier_decision_source_qwen"] = "gibberish_answer"
        if args.include_context:
            result["retrieved_context"] = raw_context
            if args.context_format != "raw":
                result["answer_context"] = answer_context

        per_query.append(result)

        print(
            f"✅ {len(per_query):>3}/{len(triples)} | {query_id} | "
            f"ext_faithful={ext['overall']['faithful']} | "
            f"qwen_faithful={qwn['overall']['faithful']}"
        )

    external_summary = _summarize(external_judgments)
    qwen_summary = _summarize(qwen_judgments)
    agreement = _judge_agreement(external_judgments, qwen_judgments)
    generation_quality = _summarize_generation_quality(per_query)
    failed_count = len(failed_queries)
    succeeded_count = len(per_query)
    run_status = {
        "attempted_queries": attempted_queries,
        "succeeded_queries": succeeded_count,
        "failed_queries": failed_count,
        "failure_rate": _safe_div(failed_count, attempted_queries),
    }

    eval_results = {
        "n_queries_attempted": attempted_queries,
        "n_queries_succeeded": succeeded_count,
        "n_queries_failed": failed_count,
        "failed_queries_preview": failed_queries[:25],
        "config": {
            "triples": str(args.triples),
            "retrieval_mode": args.retrieval_mode,
            "context_format": args.context_format,
            "dense_top_k": args.dense_top_k,
            "answer_model": args.answer_model,
            "answer_api_mode": args.answer_api_mode,
            "answer_endpoint_url": args.answer_endpoint_url,
            "answer_endpoint_model": answer_model_for_call,
            "answer_endpoint_mode": args.answer_endpoint_mode,
            "allow_endpoint_chat_fallback": args.allow_endpoint_chat_fallback,
            "external_judge_model": args.external_judge_model,
            "qwen_judge_model": args.qwen_judge_model,
            "judge_max_tokens": args.judge_max_tokens,
            "answer_max_tokens": args.answer_max_tokens,
            "sleep_seconds": args.sleep_seconds,
            "judge_retries": args.judge_retries,
            "judge_retry_delay": args.judge_retry_delay,
            "include_context": args.include_context,
            "max_queries": args.max_queries,
            "evaluated_at": datetime.now().isoformat(timespec="seconds"),
        },
        "summary": {
            "run_status": run_status,
            "primary_faithfulness_metric": {
                "judge": "external",
                "unfaithful_claim_rate": external_summary["unfaithful_claim_rate"],
                "contradicted_claim_rate": external_summary["contradicted_claim_rate"],
                "not_found_claim_rate": external_summary["not_found_claim_rate"],
                "query_faithfulness_rate": external_summary["query_faithfulness_rate"],
                "claim_support_rate": external_summary["claim_support_rate"],
                "contradiction_weighted_hallucination": external_summary[
                    "contradiction_weighted_hallucination"
                ],
            },
            "external_judge": external_summary,
            "qwen_judge_sensitivity": qwen_summary,
            "judge_agreement": agreement,
            "generation_quality": generation_quality,
        },
        "per_query": per_query,
    }

    output_path = args.output
    if args.run_name.strip():
        safe_name = _safe_run_name(args.run_name)
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_path = DEFAULT_RESULTS_DIR / f"{safe_name}_{ts}.json"

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as fh:
        json.dump(eval_results, fh, indent=2, ensure_ascii=False)

    if args.run_name.strip():
        _append_comparison_csv(
            csv_path=DEFAULT_COMPARISON_CSV,
            run_name=_safe_run_name(args.run_name),
            output_path=output_path,
            eval_results=eval_results,
        )

    print("\n════════════════════════════════════════════════════")
    print(
        "Run status: "
        f"attempted={run_status['attempted_queries']}, "
        f"succeeded={run_status['succeeded_queries']}, "
        f"failed={run_status['failed_queries']}, "
        f"failure_rate={run_status['failure_rate']:.3f}"
    )
    print("Primary metric (external judge):")
    print(
        "  unfaithful_claim_rate="
        f"{external_summary['unfaithful_claim_rate']:.3f}, "
        "contradicted_claim_rate="
        f"{external_summary['contradicted_claim_rate']:.3f}, "
        "not_found_claim_rate="
        f"{external_summary['not_found_claim_rate']:.3f}, "
        "query_faithfulness_rate="
        f"{external_summary['query_faithfulness_rate']:.3f}, "
        "claim_support_rate="
        f"{external_summary['claim_support_rate']:.3f}, "
        "contradiction_weighted_hallucination="
        f"{external_summary['contradiction_weighted_hallucination']:.3f}"
    )
    print("Sensitivity (Qwen judge):")
    print(
        "  unfaithful_claim_rate="
        f"{qwen_summary['unfaithful_claim_rate']:.3f}, "
        "contradicted_claim_rate="
        f"{qwen_summary['contradicted_claim_rate']:.3f}, "
        "not_found_claim_rate="
        f"{qwen_summary['not_found_claim_rate']:.3f}, "
        "query_faithfulness_rate="
        f"{qwen_summary['query_faithfulness_rate']:.3f}, "
        "claim_support_rate="
        f"{qwen_summary['claim_support_rate']:.3f}, "
        "contradiction_weighted_hallucination="
        f"{qwen_summary['contradiction_weighted_hallucination']:.3f}"
    )
    print(
        "Judge agreement: "
        f"faithful_label={agreement['faithful_label_agreement']:.3f}, "
        f"unfaithful_presence={agreement['unfaithful_presence_agreement']:.3f}"
    )
    print(
        "Generation quality: "
        f"answer_relevance={generation_quality['answer_relevance']:.3f}, "
        f"completeness={generation_quality['completeness']:.3f}, "
        f"conciseness={generation_quality['conciseness']:.3f}, "
        f"answer_correctness_token_f1={generation_quality['answer_correctness_token_f1']:.3f}, "
        f"exact_match_rate={generation_quality['answer_correctness_exact_match_rate']:.3f}"
    )
    print(
        "End-to-end efficiency: "
        f"latency_total_p95_ms={generation_quality['latency_total_p95_ms']:.1f}, "
        f"avg_retrieved_tokens={generation_quality['avg_retrieved_tokens']:.1f}, "
        f"avg_answer_tokens={generation_quality['avg_answer_tokens']:.1f}, "
        "answer_tokens_per_retrieved_token="
        f"{generation_quality['answer_tokens_per_retrieved_token']:.3f}"
    )
    print(f"Results saved: {output_path}")
    if args.run_name.strip():
        print(f"Comparison CSV updated: {DEFAULT_COMPARISON_CSV}")


if __name__ == "__main__":
    main()
